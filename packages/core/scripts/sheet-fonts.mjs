#!/usr/bin/env node
/**
 * Writes src/emit/htmlSheet.fonts.ts: the workbench's bundled fonts (apps/web/src/fonts, see its
 * PROVENANCE.md) as base64 @font-face rules, so the passport sheet renders in the workbench's
 * type on any machine without fetching anything (ADR D-053). Run after the web app's fonts
 * change; emit.htmlSheet.test.ts fails while the two disagree.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fontDir = join(here, '..', '..', '..', 'apps', 'web', 'src', 'fonts');
const outfile = join(here, '..', 'src', 'emit', 'htmlSheet.fonts.ts');

// Space Mono bold is left out: the sheet sets mono text in the regular weight only.
const FACES = [
  { family: 'Space Grotesk', file: 'space-grotesk.woff2', weight: '300 700' },
  { family: 'Space Mono', file: 'space-mono-regular.woff2', weight: '400' },
  { family: 'Doto', file: 'doto.woff2', weight: '400 900' },
];

/** The string literal as Biome formats it, so a regenerated file passes `pnpm lint` as is. */
const singleQuoted = (s) =>
  `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;

const rules = FACES.map(
  ({ family, file, weight }) =>
    `@font-face{font-family:"${family}";src:url(data:font/woff2;base64,${readFileSync(join(fontDir, file)).toString('base64')}) format("woff2");font-weight:${weight};font-display:block}`,
);

writeFileSync(
  outfile,
  `// Generated by scripts/sheet-fonts.mjs from apps/web/src/fonts. Do not edit.
// Space Grotesk, Space Mono and Doto, SIL Open Font License 1.1; sources, commit and sha256 are
// in apps/web/src/fonts/PROVENANCE.md.
export const SHEET_FONTS_CSS =
  ${singleQuoted(rules.join('\n'))};
`,
);
console.log(`wrote ${outfile}`);
